/**
 * 从 docs/recovered/imported-2026-08-09.json 生成 src/mock/dojo/imported/index.ts。
 *
 * 背景：原始 Excel（dojo 脚本.xlsx / dojo数据.xlsx）已丢失，import-excel.mjs 无法重跑。
 * 这份 JSON 是从线上 2026-08-09 构建产物里还原出来的按项目切分的数据集，已与
 * 项目 KPI 逐项核对（英国 24 条分发 / 曝光 21217 / 3 账号，德国 10 条 / 6878 / 2 账号）。
 * 拿到新 Excel 后应改回 import-excel.mjs，本脚本即可废弃。
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = resolve(here, '../..')
const SRC = resolve(repoRoot, 'docs/recovered/imported-2026-08-09.json')
const OUT = resolve(here, '../src/mock/dojo/imported/index.ts')
const OUT_SUMMARY = resolve(here, '../src/mock/dojo/imported/summary.json')

const data = JSON.parse(readFileSync(SRC, 'utf8'))
const { timelineStart, workflowStages, accountPlans, weeklyScripts, distributionRecords, accountMonitor } = data

const lit = (v) => JSON.stringify(v, null, 2)

const allEnd = workflowStages.map((s) => s.endDate).filter(Boolean).sort()
const timelineEnd = allEnd[allEnd.length - 1] || timelineStart

const summary = {
  recoveredFrom: data.recoveredFrom,
  generatedBy: 'scripts/gen-imported.mjs',
  counts: {
    workflowStages: workflowStages.length,
    accountPlans: accountPlans.length,
    weeklyScripts: Object.fromEntries(Object.entries(weeklyScripts).map(([w, rows]) => [w, rows.length])),
    distributionRecords: distributionRecords.length,
    accountMonitor: accountMonitor.length,
    timelineStart,
    timelineEnd
  }
}

const ts = `/** AUTO-GENERATED by scripts/gen-imported.mjs — 勿手改，改 docs/recovered/*.json 后重跑脚本 */
/* eslint-disable */

export interface WorkflowStage {
  id: string
  projectId: string
  name: string
  owner: string
  status: string
  statusLabel: string
  startDate: string | null
  endDate: string | null
  markCols: number[]
}

export interface AccountPlanAccount {
  name: string
  link: string
  note: string
}

export interface AccountPlan {
  projectId: string
  segment: string
  plannedCount: number | null
  activeCount: number | null
  sceneExample: string
  accounts: AccountPlanAccount[]
}

export interface WeeklyScriptRow {
  projectId: string
  week: string
  rowIndex: number
  [key: string]: string | number
}

export interface DistributionRecord {
  id: string
  projectId: string
  account: string
  publishDate: string | null
  videoUrl: string
  naturalViews: number | null
  paidViews: number
  screenshot: string
  adCompleteTime: string
  note: string
  engagementRate: number | null
  retention3s: number | null
}

export interface AccountMonitorRow {
  account: string
  projectId: string
  postCount: number
  totalPaidViews: number
  totalNaturalViews: number
  avgEngagementRate: number | null
  avgRetention3s: number | null
  lastPublish: string | null
}

export const importSummary = ${lit(summary)} as const

export const timelineStart = ${lit(timelineStart)}
export const timelineEnd = ${lit(timelineEnd)}

export const workflowStages: WorkflowStage[] = ${lit(workflowStages)}

export const accountPlans: AccountPlan[] = ${lit(accountPlans)}

export const weeklyScripts: Record<string, WeeklyScriptRow[]> = ${lit(weeklyScripts)}

export const distributionRecords: DistributionRecord[] = ${lit(distributionRecords)}

export const accountMonitor: AccountMonitorRow[] = ${lit(accountMonitor)}
`

writeFileSync(OUT, ts, 'utf8')
writeFileSync(OUT_SUMMARY, `${lit(summary)}\n`, 'utf8')

console.log(`已生成 ${OUT}`)
console.log(`  流程阶段 ${workflowStages.length} · 账号规划 ${accountPlans.length} · 分发 ${distributionRecords.length} · 监控账号 ${accountMonitor.length}`)
console.log(`  脚本周: ${Object.entries(weeklyScripts).map(([w, r]) => `${w}=${r.length}`).join(' ')}`)
console.log(`  周期 ${timelineStart} → ${timelineEnd}`)
