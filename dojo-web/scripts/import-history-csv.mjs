/**
 * 从 docs/source/history/*.csv 生成前端可读的 historyAccounts / historyPosts
 * 运行: node scripts/import-history-csv.mjs
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.join(__dirname, '../..')
const historyDir = path.join(root, 'docs/source/history')
const outDir = path.join(__dirname, '../src/mock/dojo/imported')

function parseCsv(text) {
  const lines = text.replace(/\r\n/g, '\n').replace(/\r/g, '\n').split('\n').filter(Boolean)
  if (!lines.length) return []
  const headers = lines[0].split(',').map((h) => h.trim())
  return lines.slice(1).map((line) => {
    const cols = []
    let cur = ''
    let inQ = false
    for (let i = 0; i < line.length; i++) {
      const c = line[i]
      if (c === '"') inQ = !inQ
      else if (c === ',' && !inQ) {
        cols.push(cur)
        cur = ''
      } else cur += c
    }
    cols.push(cur)
    const row = {}
    headers.forEach((h, i) => {
      row[h] = (cols[i] || '').trim()
    })
    return row
  })
}

function num(v) {
  const n = Number(String(v || '').replace(/,/g, ''))
  return Number.isFinite(n) ? n : 0
}

function pickLatest(files, pattern) {
  const hits = files.filter((f) => pattern.test(f))
  if (!hits.length) return null
  hits.sort()
  return path.join(historyDir, hits[hits.length - 1])
}

function handleFromUrl(url) {
  const m = String(url).match(/@([^/?]+)/)
  return m ? `@${m[1]}` : url
}

function main() {
  if (!fs.existsSync(historyDir)) {
    console.error('Missing', historyDir)
    process.exit(1)
  }

  const files = fs.readdirSync(historyDir)
  const fansFile = pickLatest(files, /^账号粉丝量/)
  const postsFile = pickLatest(files, /^账号发布内容/)
  const batteryFile = files.find((f) => f.startsWith('battery-posts'))

  const issues = []
  const accounts = new Map()

  if (fansFile) {
    const rows = parseCsv(fs.readFileSync(fansFile, 'utf8'))
    for (const r of rows) {
      const link = r['账号链接'] || r.link || ''
      const handle = handleFromUrl(link)
      if (!handle) continue
      accounts.set(handle, {
        handle,
        device: r['云机编号'] || r.device || '',
        link,
        followers: num(r['粉丝量'] || r.followers),
        snapshotDate: r['日期'] || r.date || null
      })
    }
    console.log(`Fans CSV: ${rows.length} rows → ${accounts.size} accounts (${path.basename(fansFile)})`)
  } else {
    issues.push('缺少 账号粉丝量 CSV')
  }

  const posts = []
  if (postsFile) {
    const rows = parseCsv(fs.readFileSync(postsFile, 'utf8'))
    for (const r of rows) {
      const link = r['内容链接'] || r.videoUrl || ''
      const accountLink = r['账号名称'] ? '' : ''
      posts.push({
        account: r['账号名称'] || handleFromUrl(link),
        platform: r['平台'] || 'TikTok',
        publishDate: r['发布日期'] || null,
        title: r['内容标题'] || '',
        videoUrl: link,
        views: num(r['播放量']),
        likes: num(r['点赞量']),
        comments: num(r['评论量']),
        shares: num(r['转发量'])
      })
    }
    console.log(`Posts CSV: ${rows.length} rows (${path.basename(postsFile)})`)
  } else {
    issues.push('缺少 账号发布内容 CSV')
  }

  if (batteryFile) {
    console.log(`battery-posts ${batteryFile} — 可选监测库，本次未合并（需 Velix 后端）`)
  }

  const out = {
    importedAt: new Date().toISOString(),
    sources: {
      fans: fansFile ? path.basename(fansFile) : null,
      posts: postsFile ? path.basename(postsFile) : null,
      battery: batteryFile || null
    },
    counts: { accounts: accounts.size, posts: posts.length },
    issues,
    accounts: [...accounts.values()],
    posts
  }

  fs.mkdirSync(outDir, { recursive: true })
  const outPath = path.join(outDir, 'historyImport.json')
  fs.writeFileSync(outPath, JSON.stringify(out, null, 2), 'utf8')

  const tsPath = path.join(outDir, 'historyImport.ts')
  fs.writeFileSync(
    tsPath,
    `/** AUTO-GENERATED by scripts/import-history-csv.mjs — ${out.importedAt} */\n/* eslint-disable */\n\nexport const historyImport = ${JSON.stringify(out, null, 2)} as const\n`,
    'utf8'
  )

  console.log('Wrote', outPath)
  if (issues.length) console.warn('Issues:', issues)
}

main()
